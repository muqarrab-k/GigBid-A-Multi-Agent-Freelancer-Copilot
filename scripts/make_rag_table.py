import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "evals" / "results"
ORDER = ["v0", "filter", "v1", "v2", "v3", "v8", "v1_filter", "v2_filter", "v3_filter", "v8_filter",
         "v12_filter", "v123_filter", "v1238_filter"]
NA = "n/a"


def load(name: str) -> dict[str, Any] | None:
    path = RESULTS / f"rag_{name}.json"
    return json.loads(path.read_text()) if path.exists() else None


def table_row(r: dict[str, Any]) -> dict[str, Any]:
    types = r.get("per_job_type", {})
    refusal = r.get("refusal") or {}
    return {
        "variant": r["variant"],
        "components": "+".join(r.get("components") or []) or "dense",
        "recall_at_5": r["overall"]["recall_at_5"],
        "mrr": r["overall"]["mrr"],
        "ndcg_at_10": r["overall"]["ndcg_at_10"],
        "recall_at_5_4plus_reqs": types.get("4+ requirements", {}).get("recall_at_5", NA),
        "recall_at_5_under4_reqs": types.get("<4 requirements", {}).get("recall_at_5", NA),
        "per_persona_recall_at_5": {p: v["recall_at_5"] for p, v in r["per_persona"].items()},
        "p50_ms": r["latency_ms"]["p50"],
        "p95_ms": r["latency_ms"]["p95"],
        "gap_skip_refusal_rate": refusal.get("gap_skip_refusal_rate", NA),
        "bid_refusal_rate": refusal.get("bid_refusal_rate", NA),
        "unsupported_claims_per_proposal": NA,
        "judge_score": NA,
        "gigsim_reply_rate": NA,
        "reranker": r.get("reranker"),
        "source": f"evals/results/rag_{r['variant']}.json",
    }


def main() -> None:
    """Rebuild the RAG results table from evals/results/rag_*.json."""
    rows = [table_row(r) for r in (load(n) for n in ORDER) if r]
    personas = sorted({p for row in rows for p in row["per_persona_recall_at_5"]})
    head = ["Variant", "Components", "Recall@5", "MRR", "nDCG@10", "R@5 4+ reqs", "R@5 <4 reqs",
            *[f"R@5 {p}" for p in personas], "p50 ms", "p95 ms", "Refusal gap-skip", "Refusal bid",
            "Unsupported claims/proposal", "Judge", "GigSim reply rate"]
    lines = ["# RAG results (dev bid jobs, k=10)", "",
             "Generated by `scripts/make_rag_table.py` from `evals/results/rag_*.json`. Do not edit by hand.", "",
             "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for row in rows:
        cells = [row["variant"], row["components"], row["recall_at_5"], row["mrr"], row["ndcg_at_10"],
                 row["recall_at_5_4plus_reqs"], row["recall_at_5_under4_reqs"],
                 *[row["per_persona_recall_at_5"].get(p, NA) for p in personas], row["p50_ms"], row["p95_ms"],
                 row["gap_skip_refusal_rate"], row["bid_refusal_rate"], row["unsupported_claims_per_proposal"],
                 row["judge_score"], row["gigsim_reply_rate"]]
        lines.append("| " + " | ".join(str(c) for c in cells) + " |")
    ablation = RESULTS / "rag_ablation.json"
    if ablation.exists():
        ab = json.loads(ablation.read_text())
        best = ab["best"]
        lines += ["", f"## Ablation of `{best['variant']}` ({'+'.join(best['components'])})", "",
                  "| Dropped | Recall@5 | ΔRecall@5 | MRR | ΔMRR | nDCG@10 | ΔnDCG@10 | p50 ms |", "|---|---|---|---|---|---|---|---|",
                  f"| (none) | {best['recall_at_5']} | 0 | {best['mrr']} | 0 | {best['ndcg_at_10']} | 0 | "
                  f"{best['latency_ms']['p50']} |"]
        for a in ab["ablation"]:
            lines.append(f"| {a['dropped']} | {a['recall_at_5']} | {a['delta_recall_at_5']} | {a['mrr']} | "
                         f"{a['delta_mrr']} | {a['ndcg_at_10']} | {a['delta_ndcg_at_10']} | {a['latency_ms']['p50']} |")
    rerankers = sorted({str(r["reranker"]) for r in rows if r["reranker"]})
    lines += ["", f"Reranker used: {', '.join(rerankers) or NA}. Claims, judge and reply-rate columns are n/a "
              "because the proposal eval was not re-run per variant."]
    (RESULTS / "rag_results_table.md").write_text("\n".join(lines) + "\n")
    (RESULTS / "rag_results_table.json").write_text(json.dumps({"rows": rows}, indent=2))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
