from pathlib import Path

import httpx
import pandas as pd

from agent.config import ROOT
from data_pipeline.common import Source, load_sources, table_files

PROFILE_PATH = ROOT / "docs" / "data_profile.md"
KAGGLE_VIEW = "https://www.kaggle.com/api/v1/datasets/view/{slug}"
SAMPLE_ROWS = 3
MAX_CELL = 120


def fetch_license(slug: str) -> str:
    try:
        resp = httpx.get(KAGGLE_VIEW.format(slug=slug), timeout=15)
        resp.raise_for_status()
        name = resp.json().get("licenseNameNullable")
    except (httpx.HTTPError, ValueError):
        name = None
    return name or "TODO: confirm on Kaggle page"


def read_any(path: Path, nrows: int | None = None) -> pd.DataFrame:
    if path.suffix == ".csv":
        return pd.read_csv(path, nrows=nrows, low_memory=False)
    if path.suffix == ".xlsx":
        return pd.read_excel(path, nrows=nrows)
    return pd.read_parquet(path)


def short(value: object) -> str:
    text = " ".join(str(value).split()).replace("|", "/")
    return text if len(text) <= MAX_CELL else text[:MAX_CELL] + "..."


def profile_table(path: Path) -> list[str]:
    df = read_any(path)
    lines = [f"### `{path.name}`", "", f"- rows: {len(df):,}", f"- columns: {len(df.columns)}", ""]
    lines += ["| column | dtype | null % |", "|---|---|---|"]
    nulls = df.isna().mean() * 100
    for col in df.columns:
        lines.append(f"| `{col}` | {df[col].dtype} | {nulls[col]:.1f} |")

    lines += ["", f"Sample rows ({SAMPLE_ROWS}):", ""]
    sample = df.head(SAMPLE_ROWS)
    for i, (_, row) in enumerate(sample.iterrows(), start=1):
        lines.append(f"Row {i}:")
        lines += [f"- `{col}`: {short(row[col])}" for col in df.columns]
        lines.append("")
    return lines


def profile_source(source: Source) -> list[str]:
    lines = [
        f"## {source.name}",
        "",
        f"- Kaggle: [{source.slug}]({source.url})",
        f"- license: {fetch_license(source.slug)}",
        f"- origin: {source.origin.upper()}",
        "",
    ]
    files = table_files(source)
    if not files:
        return lines + ["MISSING: no data files found.", ""]
    for path in files:
        # skip excel twin
        if path.suffix == ".xlsx" and path.with_suffix(".csv").exists():
            lines += [f"### `{path.name}`", "", "Skipped: same data as the CSV.", ""]
            continue
        print(f"profiling {source.name}/{path.name}")
        lines += profile_table(path)
    return lines


def main() -> None:
    lines = ["# Data profile", "", "Generated by `python -m data_pipeline.inspect`.", ""]
    for source in load_sources():
        lines += profile_source(source)
    PROFILE_PATH.write_text("\n".join(lines) + "\n")
    print(f"wrote {PROFILE_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
