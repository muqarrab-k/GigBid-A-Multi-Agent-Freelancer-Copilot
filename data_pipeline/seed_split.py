import numpy as np
import pandas as pd

from agent.config import DataConfig, get_config
from data_pipeline.common import PROCESSED_DIR, REAL_SEED_DIR
from data_pipeline.schema import MarketJob

BUCKETS = ("ai_ml", "fullstack", "data_analyst", "off_topic")
SPLITS = ("history", "stream", "dev_pool")


def primary_bucket(tags: list[str] | np.ndarray | None) -> str:
    items = list(tags) if tags is not None else []
    return str(items[0]) if items else "off_topic"


def bucket_targets(size: int, off_topic_share: float) -> dict[str, int]:
    off = round(size * off_topic_share)
    each, extra = divmod(size - off, 3)
    targets = {b: each + (1 if i < extra else 0) for i, b in enumerate(BUCKETS[:3])}
    targets["off_topic"] = off
    return targets


def split_jobs(jobs: pd.DataFrame, cfg: DataConfig) -> dict[str, pd.DataFrame]:
    """Disjoint seeded splits by dup_group, balanced by persona."""
    words = jobs["description"].fillna("").str.split().str.len()
    jobs = jobs[words >= cfg.min_description_words].copy()
    jobs["bucket"] = jobs["persona_tags"].map(primary_bucket)
    jobs["desc_len"] = jobs["description"].fillna("").str.len()

    # best row per group
    ranked = jobs.sort_values(["dup_group", "desc_len", "job_id"], ascending=[True, False, True])
    reps = ranked.drop_duplicates("dup_group")

    rng = np.random.default_rng(cfg.seed)
    order = rng.permutation(len(reps))
    reps = reps.iloc[order]

    sizes = cfg.split_sizes.model_dump()
    used: set[str] = set()
    out: dict[str, pd.DataFrame] = {}
    for split in SPLITS:
        picked = []
        for bucket, target in bucket_targets(sizes[split], cfg.off_topic_share).items():
            pool = reps[(reps["bucket"] == bucket) & ~reps["dup_group"].isin(used)]
            chosen = pool.head(target)
            used.update(chosen["dup_group"])
            picked.append(chosen)
        groups = pd.concat(picked)["dup_group"]
        if split == "stream":
            # keep reposts
            rows = ranked[ranked["dup_group"].isin(groups)]
            rows = rows.groupby("dup_group", sort=False).head(cfg.stream_dup_cap)
        else:
            rows = reps[reps["dup_group"].isin(groups)]
        rows = rows.sample(frac=1, random_state=cfg.seed)
        out[split] = rows.drop(columns=["bucket", "desc_len"]).reset_index(drop=True)
    return out


def plain(value: object) -> object:
    """Numpy and pandas values to plain Python."""
    if isinstance(value, np.ndarray | list):
        return list(value)
    if pd.isna(value):
        return None
    if isinstance(value, pd.Timestamp):
        return value.to_pydatetime()
    return value


def write_jsonl(df: pd.DataFrame, path: str) -> None:
    """Re-validate each row as a MarketJob."""
    with open(path, "w", encoding="utf-8") as f:
        for record in df[list(MarketJob.model_fields)].to_dict(orient="records"):
            job = MarketJob.model_validate({k: plain(v) for k, v in record.items()})
            f.write(job.model_dump_json(exclude={"client_id"}) + "\n")


def splits_report(splits: dict[str, pd.DataFrame], cfg: DataConfig) -> str:
    lines = [
        "# GigSim seed splits",
        "",
        f"Generated by `python -m data_pipeline.seed_split` with seed {cfg.seed}.",
        "All rows are REAL Kaggle job posts (see docs/DATA_CARD.md). Splits share no dup_group.",
        "",
        "| split | rows | groups | dup rows | ai_ml | fullstack | data_analyst | off_topic |"
        " fixed | hourly | unknown budget |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name, df in splits.items():
        buckets = df["persona_tags"].map(primary_bucket).value_counts()
        kinds = df["budget_type"].fillna("unknown").value_counts()
        groups = df["dup_group"].nunique()
        cells = [name, len(df), groups, len(df) - groups]
        cells += [buckets.get(b, 0) for b in BUCKETS]
        cells += [kinds.get(k, 0) for k in ("fixed", "hourly", "unknown")]
        lines.append("| " + " | ".join(str(c) for c in cells) + " |")

    lines += ["", "Rows per source:", ""]
    for name, df in splits.items():
        counts = ", ".join(f"{k}: {v}" for k, v in df["source"].value_counts().items())
        lines.append(f"- {name}: {counts}")
    lines += ["", "Persona = first tag from `data_pipeline/persona_keywords.yaml`; jobs can have more."]
    return "\n".join(lines) + "\n"


def main() -> dict[str, pd.DataFrame]:
    cfg = get_config().data
    jobs = pd.read_parquet(PROCESSED_DIR / "jobs.parquet")
    splits = split_jobs(jobs, cfg)
    REAL_SEED_DIR.mkdir(parents=True, exist_ok=True)
    for name, df in splits.items():
        write_jsonl(df, str(REAL_SEED_DIR / f"jobs_{name}.jsonl"))
        print(f"  {name:<9} {len(df):>5} rows")
    (REAL_SEED_DIR / "SPLITS.md").write_text(splits_report(splits, cfg))
    return splits


if __name__ == "__main__":
    main()
